package socialnetwork.repository.database;

import socialnetwork.domain.Utilizator;
import socialnetwork.domain.validators.ValidationException;
import socialnetwork.domain.validators.Validator;
import socialnetwork.exceptions.RepositoryException;
import socialnetwork.repository.PagingRepository;
import socialnetwork.util.paging.Page;
import socialnetwork.util.paging.Pageable;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Repository of users kept in the PostgreSQL table {@code users}, with JDBC.
 * <p>
 * The id of a new user is generated by the database
 * ({@code GENERATED ALWAYS AS IDENTITY}) and is set on the user by
 * {@link #save(Utilizator)}. Every method opens its own {@link Connection},
 * {@link PreparedStatement} and {@link ResultSet} in try-with-resources, and the
 * values are always sent as parameters ({@code ?}), never concatenated in the
 * SQL text. A {@link SQLException} is converted into a {@link RepositoryException}.
 * <p>
 * {@link #findAllOnPage(Pageable)} returns one page of users, paginated in SQL
 * with {@code ORDER BY id LIMIT ? OFFSET ?}.
 * <p>
 * The users returned by {@link #findAll()}, {@link #findOne(Long)} and
 * {@link #findAllOnPage(Pageable)} also have
 * their friend list filled from the table {@code friendships}, so the service
 * and the search criteria work the same as with the other kinds of persistence.
 */
public class UtilizatorDbRepository implements PagingRepository<Long, Utilizator> {
    /** Selects all the users, ordered by id. */
    private static final String SELECT_ALL = "SELECT id, first_name, last_name FROM users ORDER BY id";
    /** Selects all the friendships, to fill the friend lists. */
    private static final String SELECT_ALL_FRIENDSHIPS = "SELECT id1, id2 FROM friendships";
    /** Selects one user by id. */
    private static final String SELECT_ONE = "SELECT id, first_name, last_name FROM users WHERE id = ?";
    /** Selects the friends of one user. */
    private static final String SELECT_FRIENDS = "SELECT u.id, u.first_name, u.last_name "
            + "FROM friendships f JOIN users u ON u.id = CASE WHEN f.id1 = ? THEN f.id2 ELSE f.id1 END "
            + "WHERE f.id1 = ? OR f.id2 = ? ORDER BY u.id";
    /** Selects one page of users, ordered by id. */
    private static final String SELECT_PAGE = "SELECT id, first_name, last_name FROM users "
            + "ORDER BY id LIMIT ? OFFSET ?";
    /** Selects the friends of the users on one page; page_id is the user on the page. */
    private static final String SELECT_PAGE_FRIENDS = "SELECT p.id AS page_id, u.id, u.first_name, u.last_name "
            + "FROM (SELECT id FROM users ORDER BY id LIMIT ? OFFSET ?) p "
            + "JOIN friendships f ON f.id1 = p.id OR f.id2 = p.id "
            + "JOIN users u ON u.id = CASE WHEN f.id1 = p.id THEN f.id2 ELSE f.id1 END "
            + "ORDER BY u.id";
    /** Counts all the users. */
    private static final String COUNT = "SELECT count(*) FROM users";
    /** Inserts a user; the id is generated by the database. */
    private static final String INSERT = "INSERT INTO users (first_name, last_name) VALUES (?, ?)";
    /** Updates the names of a user. */
    private static final String UPDATE = "UPDATE users SET first_name = ?, last_name = ? WHERE id = ?";
    /** Deletes a user and returns the deleted row. */
    private static final String DELETE = "DELETE FROM users WHERE id = ? RETURNING id, first_name, last_name";

    /** The validation strategy for users. */
    private final Validator<Utilizator> validator;
    /** The JDBC url of the database. */
    private final String url;
    /** The user name for the database connection. */
    private final String user;
    /** The password for the database connection. */
    private final String password;

    /**
     * Creates the repository with the validator and the connection parameters
     * received from the factory.
     *
     * @param validator the validation strategy for users
     * @param url       the JDBC url of the database
     * @param user      the user name for the connection
     * @param password  the password for the connection
     */
    public UtilizatorDbRepository(Validator<Utilizator> validator, String url, String user, String password) {
        this.validator = validator;
        this.url = url;
        this.user = user;
        this.password = password;
    }

    /**
     * Opens a new connection to the database.
     *
     * @return the connection; the caller must close it
     * @throws SQLException if the connection cannot be opened
     */
    private Connection connect() throws SQLException {
        return DriverManager.getConnection(url, user, password);
    }

    /**
     * Builds a user from the current row of a result set.
     *
     * @param rs the result set, positioned on a row with the columns
     *           {@code id, first_name, last_name}
     * @return the user from the row, without friends
     * @throws SQLException if a column cannot be read
     */
    private static Utilizator extractUser(ResultSet rs) throws SQLException {
        Utilizator u = new Utilizator(rs.getString("first_name"), rs.getString("last_name"));
        u.setId(rs.getLong("id"));
        return u;
    }

    /**
     * Finds the user with the given id, together with his friends.
     *
     * @param id the id to look for; must not be {@code null}
     * @return the user with that id, or {@code null} if it does not exist
     * @throws IllegalArgumentException if {@code id} is {@code null}
     * @throws RepositoryException      if the database cannot be read
     */
    @Override
    public Utilizator findOne(Long id) {
        if (id == null) throw new IllegalArgumentException("id must be not null");
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(SELECT_ONE)) {
            statement.setLong(1, id);
            Utilizator found;
            try (ResultSet rs = statement.executeQuery()) {
                if (!rs.next()) return null;
                found = extractUser(rs);
            }
            try (PreparedStatement friends = connection.prepareStatement(SELECT_FRIENDS)) {
                friends.setLong(1, id);
                friends.setLong(2, id);
                friends.setLong(3, id);
                try (ResultSet rs = friends.executeQuery()) {
                    while (rs.next()) {
                        found.getFriends().add(extractUser(rs));
                    }
                }
            }
            return found;
        } catch (SQLException e) {
            throw DbErrors.wrap("cautarea utilizatorului " + id, e);
        }
    }

    /**
     * Returns all the users, ordered by id, with their friend lists filled.
     * The users and the friendships are read with the same connection, and the
     * friends of a user are the same objects as the users in the list.
     *
     * @return the list of all the users
     * @throws RepositoryException if the database cannot be read
     */
    @Override
    public Iterable<Utilizator> findAll() {
        Map<Long, Utilizator> users = new LinkedHashMap<>();
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(SELECT_ALL);
             ResultSet rs = statement.executeQuery()) {
            while (rs.next()) {
                Utilizator u = extractUser(rs);
                users.put(u.getId(), u);
            }
            try (PreparedStatement friendships = connection.prepareStatement(SELECT_ALL_FRIENDSHIPS);
                 ResultSet frs = friendships.executeQuery()) {
                while (frs.next()) {
                    Utilizator a = users.get(frs.getLong("id1"));
                    Utilizator b = users.get(frs.getLong("id2"));
                    a.getFriends().add(b);
                    b.getFriends().add(a);
                }
            }
        } catch (SQLException e) {
            throw DbErrors.wrap("citirea utilizatorilor", e);
        }
        return new ArrayList<>(users.values());
    }

    /**
     * Returns one page of users, ordered by id, with their friend lists filled.
     * The page is cut in SQL ({@code LIMIT ? OFFSET ?}); the friends of the users
     * on the page and the number of all the users ({@code count(*)}) are read
     * with the same connection.
     *
     * @param pageable which page and the size of a page; must not be {@code null}
     * @return the users on the page and the number of all the users; a page
     *         after the last one has no elements
     * @throws IllegalArgumentException if {@code pageable} is {@code null}
     * @throws RepositoryException      if the database cannot be read
     */
    @Override
    public Page<Utilizator> findAllOnPage(Pageable pageable) {
        if (pageable == null) throw new IllegalArgumentException("pageable must be not null");
        Map<Long, Utilizator> users = new LinkedHashMap<>();
        try (Connection connection = connect()) {
            try (PreparedStatement statement = connection.prepareStatement(SELECT_PAGE)) {
                statement.setInt(1, pageable.getPageSize());
                statement.setLong(2, pageable.getOffset());
                try (ResultSet rs = statement.executeQuery()) {
                    while (rs.next()) {
                        Utilizator u = extractUser(rs);
                        users.put(u.getId(), u);
                    }
                }
            }
            try (PreparedStatement statement = connection.prepareStatement(SELECT_PAGE_FRIENDS)) {
                statement.setInt(1, pageable.getPageSize());
                statement.setLong(2, pageable.getOffset());
                try (ResultSet rs = statement.executeQuery()) {
                    while (rs.next()) {
                        users.get(rs.getLong("page_id")).getFriends().add(extractUser(rs));
                    }
                }
            }
            long total;
            try (PreparedStatement statement = connection.prepareStatement(COUNT);
                 ResultSet rs = statement.executeQuery()) {
                rs.next();
                total = rs.getLong(1);
            }
            return new Page<>(new ArrayList<>(users.values()), total);
        } catch (SQLException e) {
            throw DbErrors.wrap("citirea paginii de utilizatori", e);
        }
    }

    /**
     * Validates the user and inserts it in the database. The id is generated
     * by the database, read with {@link PreparedStatement#getGeneratedKeys()}
     * and set on the given user.
     *
     * @param entity the user to save; must not be {@code null}; its id is
     *               ignored, because the database generates a new one
     * @return {@code null}, because the user is always saved with a new id
     * @throws IllegalArgumentException if {@code entity} is {@code null}
     * @throws ValidationException      if the user is not valid
     * @throws RepositoryException      if the user cannot be saved
     */
    @Override
    public Utilizator save(Utilizator entity) {
        if (entity == null) throw new IllegalArgumentException("entity must be not null");
        validator.validate(entity);
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(INSERT, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, entity.getFirstName());
            statement.setString(2, entity.getLastName());
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    entity.setId(keys.getLong(1));
                }
            }
            return null;
        } catch (SQLException e) {
            throw DbErrors.wrap("salvarea utilizatorului", e);
        }
    }

    /**
     * Deletes the user with the given id. The friendships of the user must be
     * deleted before (the service does this); otherwise the foreign keys of the
     * table {@code friendships} do not allow the deletion.
     *
     * @param id the id of the user to delete; must not be {@code null}
     * @return the deleted user, or {@code null} if it does not exist
     * @throws IllegalArgumentException if {@code id} is {@code null}
     * @throws RepositoryException      if the user cannot be deleted
     */
    @Override
    public Utilizator delete(Long id) {
        if (id == null) throw new IllegalArgumentException("id must be not null");
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(DELETE)) {
            statement.setLong(1, id);
            try (ResultSet rs = statement.executeQuery()) {
                return rs.next() ? extractUser(rs) : null;
            }
        } catch (SQLException e) {
            throw DbErrors.wrap("stergerea utilizatorului " + id, e);
        }
    }

    /**
     * Validates the user and updates its names in the database.
     *
     * @param entity the user with the new names; must not be {@code null}
     * @return {@code null} if the user was updated, otherwise the given user
     *         (there is no user with this id; {@code executeUpdate()} returned 0)
     * @throws IllegalArgumentException if {@code entity} is {@code null}
     * @throws ValidationException      if the user is not valid
     * @throws RepositoryException      if the user cannot be updated
     */
    @Override
    public Utilizator update(Utilizator entity) {
        if (entity == null) throw new IllegalArgumentException("entity must be not null");
        validator.validate(entity);
        if (entity.getId() == null) return entity;
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(UPDATE)) {
            statement.setString(1, entity.getFirstName());
            statement.setString(2, entity.getLastName());
            statement.setLong(3, entity.getId());
            return statement.executeUpdate() == 0 ? entity : null;
        } catch (SQLException e) {
            throw DbErrors.wrap("modificarea utilizatorului " + entity.getId(), e);
        }
    }
}