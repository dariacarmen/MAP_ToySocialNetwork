package socialnetwork.repository.memory;

import socialnetwork.domain.Entity;
import socialnetwork.domain.validators.ValidationException;
import socialnetwork.domain.validators.Validator;
import socialnetwork.repository.Repository;

import java.util.Collection;
import java.util.Comparator;
import java.util.HashMap;
import java.util.Map;
import java.util.function.Function;

/**
 * Implementation of {@link Repository} that keeps the entities in memory,
 * in a {@link HashMap}.
 * <p>
 * The entities are validated with the {@link Validator} strategy received in
 * the constructor, before every save and update.
 * <p>
 * The repository can generate the id of a new entity: if an id generator is
 * given in the constructor, {@link #save(Entity)} calls it for every entity
 * saved without an id. This way the id is generated by the storage, not by
 * the service (laboratory 5).
 *
 * @param <ID> the type of the identifier of the entities
 * @param <E>  the type of the entities; it must extend {@link Entity}
 */
public class InMemoryRepository<ID, E extends Entity<ID>> implements Repository<ID, E> {
    /** The validation strategy used on save and update. */
    private final Validator<E> validator;
    /** The entities, indexed by their identifier. */
    protected final Map<ID, E> entities = new HashMap<>();
    /**
     * Computes the id of a new entity from the entities already saved, or
     * {@code null} if the entities must always come with an id.
     */
    private final Function<Collection<E>, ID> idGenerator;

    /**
     * Creates an empty repository that uses the given validator. The entities
     * must always be saved with an id.
     *
     * @param validator the validation strategy for the entities
     */
    public InMemoryRepository(Validator<E> validator) {
        this(validator, null);
    }

    /**
     * Creates an empty repository that uses the given validator and generates
     * the ids of the new entities with the given function.
     *
     * @param validator   the validation strategy for the entities
     * @param idGenerator receives the entities already saved and returns the id
     *                    for a new entity; {@code null} if the entities must
     *                    always be saved with an id
     */
    public InMemoryRepository(Validator<E> validator, Function<Collection<E>, ID> idGenerator) {
        this.validator = validator;
        this.idGenerator = idGenerator;
    }

    /**
     * Id generator for entities with {@code Long} ids: returns the largest id
     * already used plus one, or 1 if there are no entities.
     *
     * @param entities the entities already saved
     * @return the id for a new entity
     */
    public static Long nextLongId(Collection<? extends Entity<Long>> entities) {
        return entities.stream()
                .map(Entity::getId)
                .max(Comparator.naturalOrder())
                .map(max -> max + 1)
                .orElse(1L);
    }

    /**
     * Finds the entity with the given identifier.
     *
     * @param id the identifier to look for; must not be {@code null}
     * @return the entity with that identifier, or {@code null} if it does not exist
     * @throws IllegalArgumentException if {@code id} is {@code null}
     */
    @Override
    public E findOne(ID id) {
        if (id == null) throw new IllegalArgumentException("id must be not null");
        return entities.get(id);
    }

    /**
     * Returns all the entities.
     *
     * @return all the entities kept in memory
     */
    @Override
    public Iterable<E> findAll() {
        return entities.values();
    }

    /**
     * Validates and saves a new entity. If the entity has no id and the
     * repository has an id generator, the generated id is set on the entity.
     *
     * @param entity the entity to save; must not be {@code null}
     * @return {@code null} if the entity was saved, otherwise the given entity
     *         (an entity with the same id already exists)
     * @throws ValidationException      if the entity is not valid
     * @throws IllegalArgumentException if {@code entity} is {@code null}, or it
     *                                  has no id and the repository cannot
     *                                  generate one
     */
    @Override
    public E save(E entity) {
        if (entity == null) throw new IllegalArgumentException("entity must be not null");
        validator.validate(entity);
        if (entity.getId() == null) {
            if (idGenerator == null) throw new IllegalArgumentException("id must be not null");
            entity.setId(idGenerator.apply(entities.values()));
        }
        if (entities.containsKey(entity.getId())) return entity;
        entities.put(entity.getId(), entity);
        return null;
    }

    /**
     * Removes the entity with the given identifier.
     *
     * @param id the identifier of the entity to remove; must not be {@code null}
     * @return the removed entity, or {@code null} if it does not exist
     * @throws IllegalArgumentException if {@code id} is {@code null}
     */
    @Override
    public E delete(ID id) {
        if (id == null) throw new IllegalArgumentException("id must be not null");
        return entities.remove(id);
    }

    /**
     * Validates the entity and replaces the existing one with the same id.
     *
     * @param entity the new entity; must not be {@code null}
     * @return {@code null} if the entity was updated, otherwise the given entity
     *         (there is no entity with this id)
     * @throws ValidationException      if the entity is not valid
     * @throws IllegalArgumentException if {@code entity} is {@code null}
     */
    @Override
    public E update(E entity) {
        if (entity == null) throw new IllegalArgumentException("entity must be not null");
        validator.validate(entity);
        if (!entities.containsKey(entity.getId())) return entity;
        entities.put(entity.getId(), entity);
        return null;
    }
}